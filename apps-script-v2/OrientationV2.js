function v2OrientationReportFormatDateTime_(value) {
  if (!value) return '-';
  const tz = CONFIG.timezone || Session.getScriptTimeZone() || 'Asia/Kuala_Lumpur';
  const d = Object.prototype.toString.call(value) === '[object Date]' ? value : new Date(value);
  if (isNaN(d.getTime())) return String(value || '-');
  return Utilities.formatDate(d, tz, 'd MMMM yyyy, h:mm a');
}

function v2OrientationReportSessionDate_(session) {
  const start = v2OrientationSessionStart_(session);
  return start ? v2OrientationReportFormatDateTime_(start) : String(session['Session Date'] || '-');
}

