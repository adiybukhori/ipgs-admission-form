function v2OrientationAssignmentActive_(row) {
  const status = String(row && row['Assignment Status'] || '').trim().toUpperCase();
  return !status || status === 'ACTIVE';
}

function v2OrientationEnsureHeaders_() {
  const ss = SpreadsheetApp.openById(CONFIG.spreadsheetId);
  const sessions = ss.getSheetByName('V2_ORIENTATION_SESSIONS');
  const tracking = ss.getSheetByName('V2_ORIENTATION_TRACKING');
  if (!sessions || !tracking) throw new Error('Orientation foundation sheets are missing.');
  v2EnsureHeaders_(sessions, V2_ORIENTATION_SESSION_HEADERS);
  v2EnsureHeaders_(tracking, V2_ORIENTATION_TRACKING_HEADERS);
  return {sessions:sessions, tracking:tracking};
}

function v2CreateOrientationSession_(data, actor) {
  v2OrientationEnsureHeaders_();
  const name = v2Required_(data.name, 'Orientation Name');
  const intakeId = v2Required_(data.intakeId, 'Intake ID');
  const sessionDate = v2Required_(data.sessionDate, 'Session Date');
  const mode = String(data.mode || 'ONLINE').trim().toUpperCase();
  if (['ONLINE','PHYSICAL','HYBRID'].indexOf(mode) < 0) throw new Error('Orientation mode must be Online, Physical or Hybrid.');

  // Fixed production cadence: 3 days, 2 days, 1 day and approximately 1 hour before.
  const reminderDays = 3;
  const now = new Date().toISOString();
  const id = String(data.sessionId || (
    'ORI-' + String(sessionDate).replace(/[^0-9]/g,'') + '-' + Utilities.getUuid().slice(0,6).toUpperCase()
  )).trim();

  const existing = v2Find_('V2_ORIENTATION_SESSIONS','Orientation Session ID',id);
  const createdAt = existing ? String(existing.record['Created At'] || now) : now;
  const createdBy = existing ? String(existing.record['Created By'] || actor || 'Admin Portal V2') : (actor || 'Admin Portal V2');

  const row = {
    'Orientation Session ID':id,
    'Orientation Name':name,
    'Intake ID':intakeId,
    'Programme Group':String(data.programmeGroup || 'ALL').trim() || 'ALL',
    'Session Date':sessionDate,
    'Start Time':String(data.startTime || '08:30').trim(),
    'End Time':String(data.endTime || '10:30').trim(),
    'Mode':mode,
    'Venue':String(data.venue || '').trim(),
    'Meeting Link':String(data.meetingLink || '').trim(),
    'Feedback Form URL':String(data.feedbackFormUrl || '').trim(),
    'Recording URL':String(data.recordingUrl || '').trim(),
    'Registrar Community URL':String(data.registrarCommunityUrl || '').trim(),
    'Programme Community URL':String(data.programmeCommunityUrl || '').trim(),
    'Reminder Days':reminderDays,
    'Status':String(data.status || 'SCHEDULED').trim().toUpperCase(),
    'Assigned Count':existing ? Number(existing.record['Assigned Count'] || 0) : 0,
    'Invitation Count':existing ? Number(existing.record['Invitation Count'] || 0) : 0,
    'Reminder Count':existing ? Number(existing.record['Reminder Count'] || 0) : 0,
    'Created At':createdAt,
    'Created By':createdBy,
    'Updated At':now
  };

  const saved = v2Upsert_('V2_ORIENTATION_SESSIONS','Orientation Session ID',id,row);
  const automation = v2OrientationEnsureReminderTrigger_();
  v2Audit_('', 'ORIENTATION', 'CREATE_SESSION', saved.previous || {}, row, actor || 'Admin Portal V2', 'SUCCESS',
    'Orientation reminder automation: ' + automation.status);
  v2InvalidateCache_();
  return {ok:true, created:saved.created, session:row, reminderAutomation:automation, build:V2_ORIENTATION_BUILD};
}

function v2AssignOrientationBatch_(data, actor) {
  v2OrientationEnsureHeaders_();
  const sessionId = v2Required_(data.sessionId,'Orientation Session ID');
  const session = v2Find_('V2_ORIENTATION_SESSIONS','Orientation Session ID',sessionId);
  if (!session) throw new Error('Orientation session not found.');
  const historicalOnly = data.historicalOnly === true;
  const sessionEnded = v2OrientationMarkEndedIfPast_(session, actor || 'Admin Portal V2');
  if (sessionEnded && !historicalOnly) {
    throw new Error('Orientation session has ended. New invitation emails are disabled. Use historical record mode to add a missed student without sending an email.');
  }
  if (!sessionEnded && !/SCHEDULED|OPEN|ACTIVE/i.test(String(session.record['Status'] || 'SCHEDULED'))) {
    throw new Error('Orientation session is not open for student assignment.');
  }

  const references = Array.from(new Set((data.referenceNos || []).map(function(v){ return String(v || '').trim(); }).filter(Boolean)));
  if (!references.length) throw new Error('Select at least one accepted student.');
  if (references.length > 100) throw new Error('Assign a maximum of 100 students at one time.');

  const assigned = [];
  const skipped = [];
  const failed = [];
  const alreadyAssignedRefs = {};
  v2Rows_('V2_ORIENTATION_TRACKING').forEach(function(row) {
    if (!v2OrientationAssignmentActive_(row)) return;
    const ref = String(row['Reference No'] || '').trim();
    if (ref) alreadyAssignedRefs[ref] = String(row['Orientation Session ID'] || '');
  });

  references.forEach(function(reference) {
    try {
      const workflow = v2Find_('V2_WORKFLOW','Reference No',reference);
      const application = v2Find_('V2_APPLICATIONS','Reference No',reference);
      if (!application) throw new Error('Application record not found.');

      if (alreadyAssignedRefs[reference]) {
        skipped.push({
          referenceNo:reference,
          message:'Student is already assigned to Orientation Session ' + alreadyAssignedRefs[reference] + '.'
        });
        return;
      }

      const existing = v2FindComposite_(
        'V2_ORIENTATION_TRACKING',
        ['Orientation Session ID','Reference No'],
        [sessionId,reference]
      );
      const old = existing ? existing.record : {};
      const now = new Date().toISOString();
      const oldWasActive = v2OrientationAssignmentActive_(old);
      const priorInvitationStatus = String(old['Invitation Status'] || '').trim().toUpperCase();
      const priorReminderStatus = String(old['Reminder Status'] || '').trim().toUpperCase();
      const row = {
        'Orientation Session ID':sessionId,
        'Reference No':reference,
        'Student Name':(workflow && workflow.record['Student Name']) || application.record['Student Name'] || '',
        'Programme':(workflow && workflow.record['Programme']) || application.record['Programme'] || '',
        'Student Email':application.record['Personal Email'] || (workflow && workflow.record['Personal Email']) || '',
        'Assigned At':oldWasActive && old['Assigned At'] ? old['Assigned At'] : now,
        'Assigned By':oldWasActive && old['Assigned By'] ? old['Assigned By'] : (actor || 'Admin Portal V2'),
        'Assignment Status':'ACTIVE',
        'Assignment Updated At':now,
        'Assignment Updated By':actor || 'Admin Portal V2',
        'Moved From Session ID':oldWasActive ? (old['Moved From Session ID'] || '') : '',
        'Moved To Session ID':'',
        'Removal Reason':'',
        'Invitation Status':historicalOnly && priorInvitationStatus !== 'SENT' ? 'NOT_REQUIRED' : (oldWasActive ? (old['Invitation Status'] || 'NOT_SENT') : 'NOT_SENT'),
        'Invitation Sent At':oldWasActive ? (old['Invitation Sent At'] || '') : '',
        'Invitation Delivery Detail':historicalOnly && priorInvitationStatus !== 'SENT' ? 'HISTORICAL_RECORD_ONLY' : (oldWasActive ? (old['Invitation Delivery Detail'] || '') : ''),
        'Reminder Status':historicalOnly && priorReminderStatus !== 'SENT' ? 'NOT_REQUIRED' : (oldWasActive ? (old['Reminder Status'] || 'NOT_SENT') : 'NOT_SENT'),
        'Reminder Sent At':oldWasActive ? (old['Reminder Sent At'] || '') : '',
        'Reminder History JSON':oldWasActive ? (old['Reminder History JSON'] || '{}') : '{}',
        'Last Reminder Milestone':old['Last Reminder Milestone'] || '',
        'Feedback Submitted':old['Feedback Submitted'] || 'NO',
        'Attendance Status':old['Attendance Status'] || 'NOT_UPDATED',
        'Feedback Submitted At':old['Feedback Submitted At'] || '',
        'Recording Email Status':old['Recording Email Status'] || 'NOT_SENT',
        'Community Email Status':old['Community Email Status'] || 'NOT_SENT',
        'Academic Handover Status':old['Academic Handover Status'] || 'NOT_READY',
        'Last Updated':now
      };

      v2UpsertComposite_(
        'V2_ORIENTATION_TRACKING',
        ['Orientation Session ID','Reference No'],
        [sessionId,reference],
        row
      );
      if (workflow) {
        v2UpdateRow_(workflow.sheet,workflow.rowNumber,{
          'Orientation Session ID':sessionId,
          'Orientation Status':'ASSIGNED',
          'Last Updated':now,
          'Updated By':actor || 'Admin Portal V2'
        });
      }

      const invitation = historicalOnly
        ? {sent:false,status:'HISTORICAL_RECORD_ONLY',mode:v2NotificationMode_()}
        : {sent:false,status:'NOT_SENT',mode:v2NotificationMode_()};

      v2Audit_(reference,'ORIENTATION','ASSIGN_STUDENT',{},{
        sessionId:sessionId,
        invitationStatus:invitation.status,
        invitationSent:false,
        historicalOnly:historicalOnly
      },actor || 'Admin Portal V2','SUCCESS',
        historicalOnly ? 'Historical record only. No invitation email sent.' : 'Student assigned only. Invitation email requires Send Invitation action.');
      assigned.push({referenceNo:reference, invitationSent:false, invitationStatus:invitation.status});
    } catch (error) {
      failed.push({referenceNo:reference, message:String(error && error.message || error)});
    }
  });

  v2OrientationRecountSession_(sessionId);
  if (!historicalOnly) v2OrientationEnsureReminderTrigger_();
  v2InvalidateCache_();
  return {
    ok:true,
    completed:failed.length === 0,
    partial:failed.length > 0 && assigned.length > 0,
    assignedCount:assigned.length,
    invitationSentCount:assigned.filter(function(x){return x.invitationSent;}).length,
    assigned:assigned,
    skipped:skipped,
    failed:failed,
    sessionId:sessionId,
    historicalOnly:historicalOnly,
    build:V2_ORIENTATION_BUILD
  };
}

function v2SendOrientationInvitation_(data, actor) {
  v2OrientationEnsureHeaders_();
  const sessionId = v2Required_(data.sessionId,'Orientation Session ID');
  const session = v2Find_('V2_ORIENTATION_SESSIONS','Orientation Session ID',sessionId);
  if (!session) throw new Error('Orientation session not found.');
  if (v2OrientationMarkEndedIfPast_(session, actor || 'Admin Portal V2') ||
      ['ENDED','CANCELLED','CLOSED'].indexOf(String(session.record['Status'] || '').toUpperCase()) >= 0) {
    throw new Error('Orientation session has ended. Invitation sending is disabled.');
  }

  const rows = v2Rows_('V2_ORIENTATION_TRACKING').filter(function(row){
    return String(row['Orientation Session ID'] || '') === sessionId && v2OrientationAssignmentActive_(row);
  });
  if (!rows.length) throw new Error('No students are assigned to this Orientation Session.');

  let sentCount = 0;
  let skippedCount = 0;
  let failedCount = 0;
  const details = [];

  rows.forEach(function(row) {
    const status = String(row['Invitation Status'] || 'NOT_SENT').trim().toUpperCase();
    if (status === 'SENT' || status === 'NOT_REQUIRED') {
      skippedCount += 1;
      details.push({referenceNo:row['Reference No'],status:'SKIPPED_'+status});
      return;
    }

    try {
      const delivery = v2OrientationSendStudentEmail_(session.record, row, 'INVITATION');
      const current = v2FindComposite_(
        'V2_ORIENTATION_TRACKING',
        ['Orientation Session ID','Reference No'],
        [sessionId,row['Reference No']]
      );
      const now = new Date().toISOString();
      const nextStatus = delivery.sent ? 'SENT' : (delivery.status === 'DISABLED' ? 'DISABLED' : 'FAILED');
      if (current) {
        v2UpdateRow_(current.sheet,current.rowNumber,{
          'Invitation Status':nextStatus,
          'Invitation Sent At':delivery.sent ? now : String(current.record['Invitation Sent At'] || ''),
          'Invitation Delivery Detail':String(delivery.status || ''),
          'Last Updated':now
        });
      }
      if (delivery.sent) sentCount += 1;
      else failedCount += 1;
      details.push({referenceNo:row['Reference No'],status:nextStatus,deliveryStatus:String(delivery.status || '')});
    } catch (error) {
      failedCount += 1;
      details.push({referenceNo:row['Reference No'],status:'FAILED',message:String(error && error.message || error)});
    }
  });

  v2OrientationRecountSession_(sessionId);
  v2OrientationEnsureReminderTrigger_();
  v2Audit_('','ORIENTATION','SEND_INVITATION',{},{
    sessionId:sessionId,
    sentCount:sentCount,
    skippedCount:skippedCount,
    failedCount:failedCount
  },actor || 'Admin Portal V2','SUCCESS','Invitation sent only to students not previously marked SENT.');
  v2InvalidateCache_();

  return {
    ok:true,
    sessionId:sessionId,
    sentCount:sentCount,
    skippedCount:skippedCount,
    failedCount:failedCount,
    details:details,
    build:V2_ORIENTATION_BUILD
  };
}

function v2RemoveOrientationStudent_(data, actor) {
  v2OrientationEnsureHeaders_();
  const sessionId = v2Required_(data.sessionId,'Orientation Session ID');
  const reference = v2Required_(data.referenceNo,'Reference No');
  const tracking = v2FindComposite_(
    'V2_ORIENTATION_TRACKING',
    ['Orientation Session ID','Reference No'],
    [sessionId,reference]
  );
  if (!tracking) throw new Error('Orientation student assignment not found.');
  if (!v2OrientationAssignmentActive_(tracking.record)) throw new Error('Student is no longer active in this Orientation Session.');

  const now = new Date().toISOString();
  const reason = String(data.reason || 'Removed from Orientation Session by Registry').trim();
  v2UpdateRow_(tracking.sheet,tracking.rowNumber,{
    'Assignment Status':'REMOVED',
    'Assignment Updated At':now,
    'Assignment Updated By':actor || 'Admin Portal V2',
    'Moved To Session ID':'',
    'Removal Reason':reason,
    'Attendance Token':'',
    'Last Updated':now
  });

  const workflow = v2Find_('V2_WORKFLOW','Reference No',reference);
  if (workflow && String(workflow.record['Orientation Session ID'] || '') === sessionId) {
    v2UpdateRow_(workflow.sheet,workflow.rowNumber,{
      'Orientation Session ID':'',
      'Orientation Status':'UNASSIGNED',
      'Last Updated':now,
      'Updated By':actor || 'Admin Portal V2'
    });
  }

  v2OrientationRecountSession_(sessionId);
  v2Audit_(reference,'ORIENTATION','REMOVE_STUDENT',tracking.record,{
    sessionId:sessionId,assignmentStatus:'REMOVED',reason:reason
  },actor || 'Admin Portal V2','SUCCESS','Student removed from active session list. Historical tracking retained.');
  v2InvalidateCache_();
  return {ok:true,sessionId:sessionId,referenceNo:reference,assignmentStatus:'REMOVED'};
}

function v2MoveOrientationStudent_(data, actor) {
  v2OrientationEnsureHeaders_();
  const sourceSessionId = v2Required_(data.sourceSessionId,'Source Orientation Session ID');
  const targetSessionId = v2Required_(data.targetSessionId,'Target Orientation Session ID');
  const reference = v2Required_(data.referenceNo,'Reference No');
  if (sourceSessionId === targetSessionId) throw new Error('Select a different target Orientation Session.');

  const sourceSession = v2Find_('V2_ORIENTATION_SESSIONS','Orientation Session ID',sourceSessionId);
  const targetSession = v2Find_('V2_ORIENTATION_SESSIONS','Orientation Session ID',targetSessionId);
  if (!sourceSession || !targetSession) throw new Error('Source or target Orientation Session not found.');
  if (v2OrientationMarkEndedIfPast_(targetSession, actor || 'Admin Portal V2') ||
      ['ENDED','CANCELLED','CLOSED'].indexOf(String(targetSession.record['Status'] || '').toUpperCase()) >= 0) {
    throw new Error('Target Orientation Session is ended or closed. Choose an active/future session.');
  }

  const source = v2FindComposite_(
    'V2_ORIENTATION_TRACKING',
    ['Orientation Session ID','Reference No'],
    [sourceSessionId,reference]
  );
  if (!source || !v2OrientationAssignmentActive_(source.record)) throw new Error('Active source assignment not found.');

  const existingActive = v2Rows_('V2_ORIENTATION_TRACKING').filter(function(row){
    return String(row['Reference No'] || '') === reference &&
      String(row['Orientation Session ID'] || '') !== sourceSessionId &&
      v2OrientationAssignmentActive_(row);
  })[0];
  if (existingActive) throw new Error('Student is already active in Orientation Session ' + existingActive['Orientation Session ID'] + '.');

  const now = new Date().toISOString();
  const old = source.record;
  const targetExisting = v2FindComposite_(
    'V2_ORIENTATION_TRACKING',
    ['Orientation Session ID','Reference No'],
    [targetSessionId,reference]
  );

  v2UpdateRow_(source.sheet,source.rowNumber,{
    'Assignment Status':'MOVED_OUT',
    'Assignment Updated At':now,
    'Assignment Updated By':actor || 'Admin Portal V2',
    'Moved To Session ID':targetSessionId,
    'Removal Reason':'Moved to another Orientation Session',
    'Attendance Token':'',
    'Last Updated':now
  });

  const newRow = {
    'Orientation Session ID':targetSessionId,
    'Reference No':reference,
    'Student Name':old['Student Name'] || '',
    'Programme':old['Programme'] || '',
    'Student Email':old['Student Email'] || '',
    'Assigned At':now,
    'Assigned By':actor || 'Admin Portal V2',
    'Assignment Status':'ACTIVE',
    'Assignment Updated At':now,
    'Assignment Updated By':actor || 'Admin Portal V2',
    'Moved From Session ID':sourceSessionId,
    'Moved To Session ID':'',
    'Removal Reason':'',
    'Invitation Status':'NOT_SENT',
    'Invitation Sent At':'',
    'Invitation Delivery Detail':'',
    'Reminder Status':'NOT_SENT',
    'Reminder Sent At':'',
    'Reminder History JSON':'{}',
    'Last Reminder Milestone':'',
    'Attendance Token':'',
    'Attendance Source':'',
    'Attendance Submitted At':'',
    'Attendance Identifier':'',
    'Attendance Link Status':'NOT_SENT',
    'Attendance Link Sent At':'',
    'Attendance Status':'NOT_UPDATED',
    'Feedback Submitted':'NO',
    'Feedback Status':'NOT_SUBMITTED',
    'Feedback Submitted At':'',
    'Feedback JSON':'',
    'Recording Email Status':'NOT_SENT',
    'Recording Email Sent At':'',
    'Recording Delivery Detail':'',
    'Community Email Status':'NOT_SENT',
    'Academic Handover Status':'NOT_READY',
    'Last Updated':now
  };
  v2UpsertComposite_(
    'V2_ORIENTATION_TRACKING',
    ['Orientation Session ID','Reference No'],
    [targetSessionId,reference],
    newRow
  );

  const workflow = v2Find_('V2_WORKFLOW','Reference No',reference);
  if (workflow) {
    v2UpdateRow_(workflow.sheet,workflow.rowNumber,{
      'Orientation Session ID':targetSessionId,
      'Orientation Status':'ASSIGNED',
      'Last Updated':now,
      'Updated By':actor || 'Admin Portal V2'
    });
  }

  v2OrientationRecountSession_(sourceSessionId);
  v2OrientationRecountSession_(targetSessionId);
  v2Audit_(reference,'ORIENTATION','MOVE_STUDENT',old,newRow,actor || 'Admin Portal V2','SUCCESS',
    'Moved from ' + sourceSessionId + ' to ' + targetSessionId + '. No email sent automatically; target invitation remains NOT_SENT.');
  v2InvalidateCache_();
  return {
    ok:true,
    referenceNo:reference,
    sourceSessionId:sourceSessionId,
    targetSessionId:targetSessionId,
    invitationStatus:'NOT_SENT',
    emailSent:false
  };
}

function v2UpdateOrientationAttendance_(data, actor) {
  v2OrientationEnsureHeaders_();
  const sessionId = v2Required_(data.sessionId,'Orientation Session ID');
  const reference = v2Required_(data.referenceNo,'Reference No');
  const attendance = String(data.attendanceStatus || '').trim().toUpperCase();
  if (['ATTENDED','ABSENT','EXCUSED','NOT_UPDATED'].indexOf(attendance) < 0) {
    throw new Error('Invalid attendance status.');
  }

  const tracking = v2FindComposite_(
    'V2_ORIENTATION_TRACKING',
    ['Orientation Session ID','Reference No'],
    [sessionId,reference]
  );
  if (!tracking) throw new Error('Orientation tracking record not found.');
  if (!v2OrientationAssignmentActive_(tracking.record)) throw new Error('Student is no longer active in this Orientation Session.');
  const workflow = v2Find_('V2_WORKFLOW','Reference No',reference);
  const now = new Date().toISOString();
  const previousAttendance = String(tracking.record['Attendance Status'] || 'NOT_UPDATED').toUpperCase();
  v2UpdateRow_(tracking.sheet,tracking.rowNumber,{
    'Attendance Status':attendance,
    'Attendance Source':'MANUAL',
    'Manual Override At':now,
    'Manual Override By':actor || 'Admin Portal V2',
    'Manual Override From':previousAttendance,
    'Last Updated':now
  });
  if (workflow) {
    v2UpdateRow_(workflow.sheet,workflow.rowNumber,{
      'Orientation Status':attendance,
      'Last Updated':now,
      'Updated By':actor || 'Admin Portal V2'
    });
  }

  v2Audit_(reference,'ORIENTATION','UPDATE_ATTENDANCE',{},{
    sessionId:sessionId,
    attendanceStatus:attendance,
    standalone:true
  },actor || 'Admin Portal V2','SUCCESS','');
  v2InvalidateCache_();
  return {ok:true,referenceNo:reference,sessionId:sessionId,attendanceStatus:attendance,standalone:true};
}


