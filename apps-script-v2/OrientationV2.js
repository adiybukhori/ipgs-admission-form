function v2OrientationReportStyleTable_(table, header) {
  table.setBorderWidth(0.5).setBorderColor('#D9DCE3');
  for(let r=0;r<table.getNumRows();r++){
    const row=table.getRow(r);
    for(let c=0;c<row.getNumCells();c++){
      const cell=row.getCell(c);
      cell.setPaddingTop(5).setPaddingBottom(5).setPaddingLeft(6).setPaddingRight(6);
      const t=cell.editAsText();
      t.setFontFamily('Arial').setFontSize(8);
      if(header&&r===0){
        cell.setBackgroundColor('#F0ECFA');
        t.setBold(true).setForegroundColor('#2D2363');
      }else if(r%2===0){
        cell.setBackgroundColor('#FAFAFC');
      }
    }
  }
  return table;
}

